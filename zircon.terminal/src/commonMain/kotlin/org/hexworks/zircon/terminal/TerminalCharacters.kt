package org.hexworks.zircon.terminal

/**
 * The parts of Unicode's East Asian Width and combining-mark tables the renderer needs to
 * keep one tile in one cell. Code points not in either table are single width, which
 * includes CP437, box drawing and the Nerd Font private-use glyphs.
 */
public object TerminalCharacters {

    public const val REPLACEMENT: Int = 0xFFFD

    /** `true` when a terminal advances the cursor by exactly one cell for [codePoint]. */
    public fun isSingleWidth(codePoint: Int): Boolean = !isWide(codePoint) && !isZeroWidth(codePoint)

    /** East Asian Width `W` and `F`, plus emoji presentation ranges. */
    public fun isWide(codePoint: Int): Boolean = inRanges(codePoint, WIDE)

    /** Combining marks, variation selectors and format characters that take no cell. */
    public fun isZeroWidth(codePoint: Int): Boolean = inRanges(codePoint, ZERO_WIDTH)

    private fun inRanges(codePoint: Int, ranges: IntArray): Boolean {
        var low = 0
        var high = ranges.size / 2 - 1
        while (low <= high) {
            val mid = (low + high) ushr 1
            when {
                codePoint < ranges[mid * 2] -> high = mid - 1
                codePoint > ranges[mid * 2 + 1] -> low = mid + 1
                else -> return true
            }
        }
        return false
    }

